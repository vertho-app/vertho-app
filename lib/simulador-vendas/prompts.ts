export function renderPrompt(
  template: string,
  values: Record<string, unknown>,
): string {
  return template.replace(
    /\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g,
    (_match, key: string) => {
      if (!(key in values))
        throw new Error(`Variável de prompt ausente: ${key}`);
      const value = values[key];
      return (typeof value === 'string' ? value : JSON.stringify(value ?? ''))
        .replace(/\{\{/g, '{ {')
        .replace(/\}\}/g, '} }');
    },
  );
}

export function mensagensDoPrompt(
  template: string,
  values: Record<string, unknown>,
) {
  // O prefixo estável inteiro vira system. Nunca interpolar texto de participante nesta mensagem.
  const system = template.replace(
    /\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g,
    (_match, key: string) => {
      if (!Object.hasOwn(values, key))
        throw new Error(`Variável de prompt ausente: ${key}`);
      return `dados.${key}`;
    },
  );
  const ordem = [
    'briefing',
    'username',
    'userlevel',
    'seed_diversidade',
    'tracos_anteriores',
    'bloco_dinamico',
    'personagem_json',
    'fase_atual',
    'sinal_moderador',
    'violacoes_moderador',
    'historico',
    'thread_completa',
    'input_vendedor',
    'resposta_cliente',
  ];
  const dados = Object.fromEntries(
    Object.entries(values).sort(
      ([a], [b]) => ordem.indexOf(a) - ordem.indexOf(b),
    ),
  );
  const user = JSON.stringify(dados)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e');
  return { system, user };
}
